// Builds the Road to 16 guide from print.html and guide-data.js.
//
//   node content/printables/road-to-16-guide/build-guide.mjs [print|text]
//
// The Passport printable's build (content/printables/guided-childhood-passport/
// build-passport.mjs), cut to what a guide needs: three PDFs, page previews,
// and guide-text.md. Needs playwright-core and a Chrome; PW_CORE and CHROME
// override the defaults, because a worktree has no node_modules.
//
// THE PAPER SIZE IS SWAPPED, NOT SCALED. US Letter gets its own @page block and
// body.letter sizes, so its type is the same size as the A4's.
//
// IT FAILS ON A PAGE THAT OVERFLOWS. Letter is 18mm shorter than A4, and a box
// that runs into the footer on one size and not the other is easy to miss by
// eye across three files. So every sheet is measured on every variant and the
// build stops if anything ends inside the footer band.
//
// guide-text.md is every word of the guide as plain text. It is the file the
// evidence check reads and `npm run ai-tells` sweeps, so what is checked is
// exactly what prints.
//
// The finished PDFs are copied to public/printables/road-to-16/, where the
// road-to-16 magnet (lib/magnets/registry.ts) hands them over at /etsy-bonus.

import { createRequire } from 'node:module'
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import vm from 'node:vm'

const DIR = dirname(fileURLToPath(import.meta.url))
const ROOT = join(DIR, '../../..')
const only = process.argv[2]
const SLUG = 'road-to-16-guide'

// ── THE TEXT ────────────────────────────────────────────────────────────────
const loadGuide = () => {
  const ctx = { window: {} }
  vm.runInNewContext(readFileSync(join(DIR, 'guide-data.js'), 'utf8'), ctx)
  return ctx.window.GUIDE
}
const writeText = () => {
  const G = loadGuide()
  const L = []
  const para = t => L.push(t, '')
  L.push('# The Road to 16, every word as printed', '', 'Generated by build-guide.mjs from guide-data.js. Do not edit by hand.', '')
  L.push('## Cover', '', 'The Road to 16', 'The grown ups guide to the whole journey', 'Balance · Behaviour · The apps · School', 'Your reward for a Guided Childhood Passport stamped up to your child\'s age', '')
  const W = G.welcome
  L.push(`## ${W.title}`, ''); W.lines.forEach(para)
  W.parts.forEach(([t, b]) => para(`${t}: ${b}`)); para(W.holdOnto)
  L.push('## Five stages, four to sixteen', '')
  para('The same five pages as your Passport. Each stage has a focus, a device that usually fits it, and one talk that matters most.')
  G.stages.forEach(s => para(`${s.friend}, ${s.ages}, ${s.stage}. ${s.focus}. The device: ${s.device}. The talk: ${s.talk}.`))
  const B = G.balance
  L.push(`## ${B.title}`, ''); para(B.intro)
  B.kinds.forEach(([t, b]) => para(`${t}: ${b}`))
  para(`${B.firstTitle}: ${B.first}`); para(`${B.ladderTitle}: ${B.ladder}`); para(`${B.ruleTitle}: ${B.rule}`)
  L.push(`${B.phoneTitle}:`, ''); G.stages.forEach(s => para(`${s.friend}, ${s.ages}: ${s.yourPhone}`))
  const H = G.behaviour
  L.push(`## ${H.title}`, ''); para(H.intro)
  G.stages.forEach(s => { L.push(`${s.friend}, ${s.ages}:`); s.signs.forEach(t => L.push(`* ${t}`)); L.push('') })
  L.push(`${H.whenTitle}:`, ''); H.when.forEach(para); para(`Not this: ${H.notThis}`); para(H.worried)
  const A = G.apps
  L.push(`## ${A.title}`, ''); para(A.intro)
  A.list.forEach(a => {
    const s = G.stages[a.stage - 1]
    para(`${a.name}. Its own minimum age: ${a.age}. Brought up on the ${s.friend} page, ${s.ages}. ${a.rule} Lock first: ${a.lock} Watch for: ${a.watch}`)
  })
  para(`The law: ${A.lawNote}`)
  const C = G.school
  L.push(`## ${C.title}`, ''); para(C.intro)
  C.moments.forEach(m => para(`${m.title}, ${m.years}, ages ${m.ages}. ${m.body}${m.fact ? ' ' + m.fact : ''} Have ready: ${m.ready}`))
  para(C.schoolPolicy)
  const X = G.wrong
  L.push(`## ${X.title}`, ''); para(`Say this: "${X.say}"`); para(X.sayNote)
  X.steps.forEach(([t, b], i) => para(`${i + 1}. ${t}. ${b}`))
  L.push('Where to get help, in the UK:', ''); X.help.forEach(([w, h]) => para(`${w}: ${h}`))
  const Z = G.sixteen
  L.push(`## ${Z.title}`, ''); para(Z.intro); para(`Cosmo's talk: "${Z.say}"`)
  para(`${Z.auditTitle}: ${Z.audit}`); para(`${Z.talkTitle}: ${Z.talk}`)
  L.push(`${Z.questionsTitle}:`); Z.questions.forEach(q => L.push(`* ${q}`)); L.push('')
  para(`${Z.appTitle}: ${Z.app}`)
  L.push('## Sources', ''); para(G.sourcesIntro)
  G.sources.forEach(([w, h], i) => para(`${i + 1}. ${w} ${h}`))
  para('This guide is general information for families, not medical, legal or safeguarding advice about your child. If you are worried, talk to your child\'s school, your GP, or one of the services on the help page.')
  writeFileSync(join(DIR, 'guide-text.md'), L.join('\n'))
  console.log('text guide-text.md')
}
writeText()
if (only === 'text') process.exit(0)

// ── THE PDFS ────────────────────────────────────────────────────────────────
const require = createRequire(import.meta.url)
const PW = process.env.PW_CORE ?? '/Users/justinphillips/guided-childhood/node_modules/playwright-core'
const { chromium } = require(PW)
const CHROME = process.env.CHROME ?? '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'
const PAGE = { a4: '@page { size: A4; margin: 0; }', letter: '@page { size: letter; margin: 0; }' }

const browser = await chromium.launch({ executablePath: existsSync(CHROME) ? CHROME : undefined })
const ready = async page => {
  await page.evaluate(() => document.fonts.ready)
  await page.waitForFunction(() => [...document.images].every(i => i.complete && i.naturalWidth > 0))
  await page.waitForTimeout(400)
}
const setVariant = (page, paper, ink) => page.evaluate(([css, paper, ink]) => {
  document.getElementById('pagesize').textContent = css
  document.body.classList.toggle('letter', paper === 'letter')
  document.body.classList.toggle('ink', ink)
}, [PAGE[paper], paper, ink])

// Every element's foot must sit above the footer band (the bottom 13mm).
const overflow = page => page.evaluate(() => {
  const mm = 96 / 25.4, bad = []
  document.querySelectorAll('.sheet').forEach((sheet, i) => {
    if (sheet.classList.contains('cover')) return
    const limit = sheet.getBoundingClientRect().bottom - 13 * mm
    for (const el of sheet.querySelectorAll('*')) {
      if (el.closest('.footer')) continue
      const r = el.getBoundingClientRect()
      if (r.height && r.bottom > limit + 0.5) { bad.push(`page ${i + 1}: ${el.tagName.toLowerCase()} "${(el.textContent || '').trim().slice(0, 40)}" ends ${((r.bottom - limit) / mm).toFixed(1)}mm into the footer band`); break }
    }
  })
  return bad
})

mkdirSync(join(DIR, 'product'), { recursive: true })
mkdirSync(join(DIR, 'images/preview/check'), { recursive: true })
const page = await browser.newPage()
await page.goto('file://' + join(DIR, 'print.html'))
await ready(page)
const problems = []
const variant = async (paper, ink, name) => {
  await setVariant(page, paper, ink)
  await page.waitForTimeout(200)
  for (const p of await overflow(page)) problems.push(`${name}: ${p}`)
  await page.pdf({ path: join(DIR, 'product', name), preferCSSPageSize: true, printBackground: true, tagged: true })
  console.log('pdf', name)
}
await variant('a4', false, `${SLUG}-A4.pdf`)
await variant('letter', false, `${SLUG}-USLetter.pdf`)
await variant('a4', true, `${SLUG}-A4-ink-saver.pdf`)
await variant('letter', true, `${SLUG}-USLetter-ink-saver.pdf`)

// Page previews for checking by eye: A4 colour, then the ink saver and Letter.
const pv = await browser.newPage({ viewport: { width: 1300, height: 1300 }, deviceScaleFactor: 2 })
await pv.goto('file://' + join(DIR, 'print.html'))
await ready(pv)
const sheets = pv.locator('.sheet')
const n = await sheets.count()
const shoot = async (dir, prefix) => { for (let i = 0; i < n; i++) await sheets.nth(i).screenshot({ path: join(DIR, dir, `${prefix}page-${String(i + 1).padStart(2, '0')}.png`) }) }
await shoot('images/preview', '')
await setVariant(pv, 'a4', true); await shoot('images/preview/check', 'ink-')
await setVariant(pv, 'letter', false); await shoot('images/preview/check', 'letter-')
console.log('previews', n)
await browser.close()

if (problems.length) {
  console.error('\nOVERFLOW, fix before shipping:\n  ' + problems.join('\n  '))
  process.exit(1)
}

// The public copies the /etsy-bonus claim hands over.
const PUB = join(ROOT, 'public/printables/road-to-16')
mkdirSync(PUB, { recursive: true })
for (const [from, to] of [['A4', 'a4'], ['USLetter', 'letter'], ['A4-ink-saver', 'ink-a4'], ['USLetter-ink-saver', 'ink-letter']]) {
  copyFileSync(join(DIR, 'product', `${SLUG}-${from}.pdf`), join(PUB, `road-to-16-${to}.pdf`))
}
console.log('public/printables/road-to-16/ updated')
